// TCS TwinX 3.0 UI: shared helpers for the twinx-ui command (build, lint, sync, contribute).
// Node 18+, no dependencies.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

export const LIB_DIR = 'ui/twinx';          // the library, as synced into every repo
export const LOCAL_DIR = 'ui/local';        // a repo's own components, not yet in the library
export const GENERATED = 'GENERATED by twinx-ui build. Do not edit: change the component folders instead.';

export const read = (p) => fs.readFileSync(p, 'utf8');
export const exists = (p) => fs.existsSync(p);
export function write(p, s) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); }
export function writeIfChanged(p, s) { if (exists(p) && read(p) === s) return false; write(p, s); return true; }
export const posix = (p) => p.split(path.sep).join('/');
export const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex').slice(0, 16);

export function walk(dir, { skip = [] } = {}) {
  const out = [];
  if (!exists(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (skip.some((s) => posix(p).includes(s))) continue;
    if (e.isDirectory()) out.push(...walk(p, { skip }));
    else out.push(p);
  }
  return out;
}

export function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name), d = path.join(dest, e.name);
    if (e.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}

export const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// ── components ────────────────────────────────────────────────────────────
// A component is a folder with component.json, <name>.css, <name>.html (examples split by <!-- @example: Title -->)
// and optionally <name>.js. A local folder whose component.json has "extends": "<library name>" adds variants to it.
export function parseExamples(html) {
  const parts = html.split(/<!--\s*@example:\s*(.*?)\s*-->/);
  const out = [];
  for (let i = 1; i < parts.length; i += 2) {
    const [title, note] = parts[i].split('|').map((s) => s.trim());
    out.push({ title, note: note || '', html: parts[i + 1].trim() });
  }
  if (!out.length && html.trim()) out.push({ title: 'Example', note: '', html: html.trim() });
  return out;
}

export function readComponents(dir, origin, root = process.cwd()) {
  const base = path.join(dir, 'components');
  if (!exists(base)) return [];
  return fs.readdirSync(base, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => {
    const d = path.join(base, e.name);
    const metaPath = path.join(d, 'component.json');
    const problems = [];
    let meta = {};
    if (!exists(metaPath)) problems.push('missing component.json');
    else { try { meta = JSON.parse(read(metaPath)); } catch (err) { problems.push('component.json is not valid JSON: ' + err.message); } }
    const name = meta.name || e.name;
    if (name !== e.name) problems.push(`component.json name "${name}" does not match its folder "${e.name}"`);
    const css = exists(path.join(d, e.name + '.css')) ? read(path.join(d, e.name + '.css')) : '';
    const htmlFile = path.join(d, e.name + '.html');
    const html = exists(htmlFile) ? read(htmlFile) : '';
    const js = exists(path.join(d, e.name + '.js')) ? read(path.join(d, e.name + '.js')) : '';
    if (!css && !meta.extends) problems.push(`missing ${e.name}.css`);
    if (!html) problems.push(`missing ${e.name}.html with at least one <!-- @example: ... --> block`);
    for (const k of ['title', 'description', 'whenToUse']) if (!meta[k]) problems.push(`component.json needs "${k}"`);
    return {
      name, dir: d, rel: posix(path.relative(root, d)), origin, css, js, examples: parseExamples(html),
      classes: [...new Set((css.match(/\.tx-[a-z0-9_-]+/gi) || []).map((c) => c.slice(1)))],
      meta: { status: origin === 'local' ? 'experimental' : 'stable', category: 'Other', variants: [], replaces: [], ...meta, name },
      problems,
    };
  }).sort((a, b) => (a.meta.category + a.meta.title).localeCompare(b.meta.category + b.meta.title));
}

// ── bundle css ────────────────────────────────────────────────────────────
export function bundleCss(libDir, comps, { withFoundations }) {
  let out = `/* TCS TwinX 3.0 UI${withFoundations ? '' : ': local components'}. ${GENERATED} */\n`;
  if (withFoundations) {
    const fonts = read(path.join(libDir, 'tokens/fonts.css')).replace(/url\("fonts\//g, 'url("tokens/fonts/');
    out += `\n/* ── tokens/fonts.css ── */\n${fonts}\n/* ── tokens/tokens.css ── */\n${read(path.join(libDir, 'tokens/tokens.css'))}\n/* ── base.css ── */\n${read(path.join(libDir, 'base.css'))}`;
  }
  for (const c of comps) if (c.css.trim()) out += `\n/* ── ${c.name}${c.meta.extends ? ' (extends ' + c.meta.extends + ')' : ''} [${c.meta.status}] ── */\n${c.css.trim()}\n`;
  return out;
}

export function bundleJs(comps) {
  const withJs = comps.filter((c) => c.js.trim());
  if (!withJs.length) return '';
  return `/* TCS TwinX 3.0 UI: component scripts. ${GENERATED} */\n` + withJs.map((c) => `\n/* ── ${c.name} ── */\n${c.js.trim()}\n`).join('');
}

export function registry(comps, version) {
  return JSON.stringify({
    generatedBy: 'twinx-ui build', version,
    components: comps.map((c) => ({
      name: c.name, title: c.meta.title, category: c.meta.category, status: c.meta.status, origin: c.origin,
      extends: c.meta.extends || undefined, description: c.meta.description, whenToUse: c.meta.whenToUse,
      variants: c.meta.variants, a11y: c.meta.a11y, replaces: c.meta.replaces, owner: c.meta.owner, since: c.meta.since,
      classes: c.classes, examples: c.examples.map((e) => e.title), path: c.rel,
    })),
  }, null, 2) + '\n';
}

export function componentsMd(comps, version) {
  let md = `# TwinX UI components (v${version})\n\n${GENERATED}\n\nCopy the markup from each component's .html file. Classes not listed here do not exist: add a variant or a component instead of inventing one.\n`;
  let cat = '';
  for (const c of comps) {
    if (c.meta.category !== cat) { cat = c.meta.category; md += `\n## ${cat}\n`; }
    md += `\n### ${c.meta.title} \`${c.name}\`${c.origin === 'local' ? ' (local, not yet in the library)' : ''}${c.meta.extends ? ` (adds to \`${c.meta.extends}\`)` : ''}\n\n`;
    md += `${c.meta.description}\n\n- **When to use:** ${c.meta.whenToUse}\n- **Markup:** \`${c.rel}/${c.name}.html\`\n`;
    if (c.meta.variants?.length) md += `- **Variants:** ${c.meta.variants.map((v) => `\`${v.class}\` ${v.description}`).join('; ')}\n`;
    if (c.meta.a11y) md += `- **Accessibility:** ${c.meta.a11y}\n`;
    if (c.meta.replaces?.length) md += `- **Replaces old classes:** ${c.meta.replaces.map((r) => '`' + r + '`').join(', ')}\n`;
  }
  return md;
}

// ── manifest of the synced library (to detect hand edits) ─────────────────
export function manifest(dir) {
  const files = {};
  for (const f of walk(dir).sort()) { const rel = posix(path.relative(dir, f)); if (rel === '.manifest.json') continue; files[rel] = sha(fs.readFileSync(f)); }
  return files;
}
